import { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { toast } from 'sonner';
import { ClipboardList, Download, Pencil, Printer } from 'lucide-react';
import { RTO_SUPPLY_TYPE_LABEL, RtoSupplyType } from '@azad/shared';
import { apiErrorMessage } from '@/lib/api-client';
import { formatPaiseExact } from '@/lib/money';
import { printBlob, saveBlob } from '@/lib/download';
import { useAuth } from '@/features/auth/auth-context';
import { Button } from '@/components/ui/button';
import { Dialog, DialogContent, DialogDescription, DialogHeader, DialogTitle } from '@/components/ui/dialog';
import { rtoApi } from '../api';
import { useRtoInvoice } from '../hooks';
import { RtoInvoiceFormDialog } from './rto-invoice-form-dialog';

const date = (iso: string): string => new Date(iso).toLocaleDateString('en-IN');

/** Everything on an RTO invoice, with its PDF, a way to the booking, and — for the owner — edit & regenerate. */
export function RtoInvoiceDetailDialog({ id, onOpenChange }: { id: string | null; onOpenChange: (open: boolean) => void }): JSX.Element {
  const navigate = useNavigate();
  const { user, can } = useAuth();
  // Editing is the owner's alone (the server checks the role as well as rto.edit).
  const canEdit = user?.role === 'OWNER' && can('rto.edit');
  const { data: r, isLoading } = useRtoInvoice(id);
  const [editing, setEditing] = useState(false);

  const withPdf = async (consume: (b: Blob, name: string) => void): Promise<void> => {
    if (!r) return;
    try { consume(await rtoApi.pdf(r.id), `${r.invoiceNumber}.pdf`); } catch (e) { toast.error(apiErrorMessage(e)); }
  };
  const intra = r?.supplyType === RtoSupplyType.INTRA;

  return (
    <>
      <Dialog open={Boolean(id)} onOpenChange={onOpenChange}>
        <DialogContent className="max-w-xl">
          {isLoading || !r ? (
            <><DialogHeader><DialogTitle>RTO invoice</DialogTitle><DialogDescription>Loading…</DialogDescription></DialogHeader></>
          ) : (
            <>
              <DialogHeader>
                <DialogTitle>RTO invoice <span className="font-mono">{r.invoiceNumber}</span></DialogTitle>
                <DialogDescription>
                  Dated {date(r.invoiceDate)}{r.createdBy ? ` · generated by ${r.createdBy}` : ''}
                  {r.revision > 1 ? ` · revision ${r.revision}, last edited ${date(r.updatedAt)}${r.updatedBy ? ` by ${r.updatedBy}` : ''}` : ''}
                </DialogDescription>
              </DialogHeader>

              <div className="grid gap-4 text-sm sm:grid-cols-2">
                <section aria-label="Customer">
                  <p className="text-xs uppercase tracking-wide text-muted-foreground">Customer</p>
                  <p className="font-medium">{r.customer.name}</p>
                  <p className="text-muted-foreground">{r.customer.phone}</p>
                </section>
                <section aria-label="Booking">
                  <p className="text-xs uppercase tracking-wide text-muted-foreground">Booking</p>
                  <p className="font-mono">{r.booking.code}</p>
                  <p className="text-muted-foreground">{r.booking.status === 'CANCELLED' ? 'Cancelled' : 'Active'}</p>
                </section>
                <section aria-label="Delivery date">
                  <p className="text-xs uppercase tracking-wide text-muted-foreground">Delivery date</p>
                  <p>{r.deliveryDate ? r.deliveryDate.split('-').reverse().join('/') : '—'}</p>
                </section>
                <section aria-label="Insurance policy">
                  <p className="text-xs uppercase tracking-wide text-muted-foreground">Insurance policy no.</p>
                  <p className="font-mono [overflow-wrap:anywhere]">{r.policyNumber ?? '—'}</p>
                </section>
                <section aria-label="Vehicle" className="sm:col-span-2">
                  <p className="text-xs uppercase tracking-wide text-muted-foreground">Vehicle</p>
                  <p className="font-medium">{r.vehicle.model} {r.vehicle.variant} · {r.vehicle.colour}</p>
                  <p className="text-muted-foreground [overflow-wrap:anywhere]">VIN <span className="font-mono">{r.vehicle.vin}</span> · Motor <span className="font-mono">{r.vehicle.motorNumber}</span> · Battery <span className="font-mono">{r.vehicle.batteryNumber}</span>{r.hsnCode ? ` · HSN ${r.hsnCode}` : ''}</p>
                </section>
              </div>

              <dl aria-label="Invoice amount" className="space-y-1 rounded-lg bg-secondary px-4 py-3 text-sm">
                {r.discount !== '0' && (
                  <>
                    <div className="flex justify-between text-muted-foreground"><dt>List price</dt><dd className="tabular-nums">{formatPaiseExact(r.listPrice)}</dd></div>
                    <div className="flex justify-between text-muted-foreground"><dt>Discount</dt><dd className="tabular-nums">− {formatPaiseExact(r.discount)}</dd></div>
                  </>
                )}
                <div className="flex justify-between"><dt>Basic price (taxable value)</dt><dd className="tabular-nums">{formatPaiseExact(r.sellingPrice)}</dd></div>
                {intra ? (
                  <>
                    <div className="flex justify-between"><dt>CGST @ {(r.gstRate / 2).toFixed(2)}%</dt><dd className="tabular-nums">{formatPaiseExact(r.cgst)}</dd></div>
                    <div className="flex justify-between"><dt>SGST @ {(r.gstRate / 2).toFixed(2)}%</dt><dd className="tabular-nums">{formatPaiseExact(r.sgst)}</dd></div>
                  </>
                ) : (
                  <div className="flex justify-between"><dt>IGST @ {r.gstRate.toFixed(2)}%</dt><dd className="tabular-nums">{formatPaiseExact(r.igst)}</dd></div>
                )}
                <div className="flex justify-between border-t pt-1 text-base font-semibold"><dt>Total</dt><dd className="tabular-nums">{formatPaiseExact(r.total)}</dd></div>
                <p className="pt-1 text-xs text-muted-foreground">{RTO_SUPPLY_TYPE_LABEL[r.supplyType]} · GST {r.gstRate}%</p>
              </dl>

              <div className="flex flex-wrap gap-2">
                <Button variant="outline" onClick={() => { onOpenChange(false); navigate(`/bookings/${r.booking.id}`); }}><ClipboardList className="h-4 w-4" /> View booking</Button>
                <Button variant="outline" onClick={() => withPdf((b, name) => saveBlob(b, name))}><Download className="h-4 w-4" /> Download PDF</Button>
                <Button variant="outline" onClick={() => withPdf((b, name) => printBlob(b, name))}><Printer className="h-4 w-4" /> Print</Button>
                {canEdit && <Button onClick={() => setEditing(true)}><Pencil className="h-4 w-4" /> Edit &amp; regenerate</Button>}
              </div>
            </>
          )}
        </DialogContent>
      </Dialog>
      {r && canEdit && <RtoInvoiceFormDialog open={editing} onOpenChange={setEditing} invoice={r} onDone={() => undefined} />}
    </>
  );
}
